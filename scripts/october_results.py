"""Every table the report draws from the October runs, regenerated from the result files.

The delivered system was frozen on 8 October and measured on the held-back sets on
9 and 10 October. Its figures were first gathered by hand into `protocols/metrics.md`;
this script computes each of them again from the rows the runs wrote, prints them, and
writes the table bodies the report includes, so that no number in Chapter 5 is typed.

    python scripts/october_results.py                 print, and write the fragments
    python scripts/october_results.py --no-write      print only

Fragments go to Report/3_Chapters/5_Chapter_Results/Tables/ and a markdown record to
stress/results/october-tables.md. Nothing here runs a model.
"""

