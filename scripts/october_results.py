def benchmark_rules() -> None:
    from ym07.checks import load_checks, score_answer

    by_item = load_checks(ROOT / "bench" / "checks.jsonl")[0]
    runs = list(BENCHMARK_RUNS)
    # The latest run of each delivered condition, written by scripts/benchmark_run.py,
    # and of the two Opus 5 arms of E23 run through the same script on 12 October.
    for condition, label, when in (("A-r1-distill-7b", "Delivered pipeline, adapter removed", "11~October"),
                                   ("A-r1-tuned", "\\textbf{Delivered system}", "11~October"),
                                   ("A2-opus-rag", "Claude Opus 5, first system's retrieval (A2)", "12~October"),
                                   ("A3-opus-pipeline", "Claude Opus 5, delivered pipeline (A3)", "12~October")):
        found = sorted((ROOT / "runs").glob(f"*-{condition}"))
        if found:
            runs.append((label, found[-1].name, when))
    say("# 11. The benchmark's twelve calculation items, by the fixed rules")
    frag = []
    for label, run, when in runs:
        recs = {r["item_id"]: r for r in rows(ROOT / "runs" / run / "responses.jsonl")}
        scores = []
        for item, checks in by_item.items():
            answer = recs.get(item, {}).get("answer", {})
