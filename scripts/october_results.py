DELIVERED = "A-r1-tuned"
# The registered rule for "at least two worked steps" (scripts/final_results.py), applied
# to every system so the September and October figures are on one instrument.
WORKING = re.compile(r"\d[^=\n]{0,40}=\s*-?\d")
# The alternative counted on 10 October: enumerated or bulleted steps.
STEP_LINE = re.compile(r"(?m)^\s*(?:\d+[.)]|[-*•])\s+")

out_lines: list[str] = []


def say(text: str = "") -> None:
    print(text)
    out_lines.append(text)


def rows(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]


def ok(records: list[dict]) -> list[dict]:
    return [r for r in records if not r.get("error")]


def pct(part: int, whole: int, digits: int = 1) -> str:
    if not whole:
        return "n/a"
    return f"{100 * part / whole:.{digits}f}\\%"


def ci(part: int, whole: int) -> str:
    lo, hi = wilson(part, whole)
    return f"{100 * lo:.0f}--{100 * hi:.0f}\\%"


def mcnemar(a_only: int, b_only: int) -> float:
    n = a_only + b_only
    if n == 0:
        return 1.0
    k = min(a_only, b_only)
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n)


def paired_full(a: list[dict], b: list[dict], key="score", full=lambda r: r["score"] == 1.0):
    A = {r["id"]: r for r in ok(a)}
    B = {r["id"]: r for r in ok(b)}
    shared = sorted(set(A) & set(B))
    a_only = sum(1 for i in shared if full(A[i]) and not full(B[i]))
    b_only = sum(1 for i in shared if full(B[i]) and not full(A[i]))
    return len(shared), a_only, b_only, mcnemar(a_only, b_only)


def paired_correct(a: list[dict], b: list[dict]):
    return paired_full(a, b, full=lambda r: bool(r.get("correct")))


def words(text: str | None) -> int:
    return len((text or "").split())


def p_tex(p: float) -> str:
    """Display a positive small p-value without rounding it to zero."""
    return r"$<0.0001$" if p < 0.0001 else f"{p:.3g}"


def write_fragment(name: str, body: str) -> None:
    TABLES.mkdir(parents=True, exist_ok=True)
    path = TABLES / name
    path.write_text("% Generated by scripts/october_results.py from the result files. Do not edit.\n"
                    + body.rstrip() + "\n", encoding="utf-8", newline="\n")


