# --- the reuse recount ---------------------------------------------------------------------

def reuse() -> dict:
    audit = json.loads((ROOT / "revision" / "audit" / "verified-evidence.json").read_text(encoding="utf-8"))
    overlap = set(audit["bank_dependence"]["development_or_earlier_test_exact_parameter_overlap"]["ids"])
    out = {}
    for where in ("heldout", "heldout-amended"):
        a = {r["id"]: r["score"] == 1 for r in rows(RESULTS / where / "calc" / f"{A0}.jsonl")}
        b = {r["id"]: r["score"] == 1 for r in rows(RESULTS / where / "calc" / f"{A3}.jsonl")}
        unseen = [i for i in a if i not in overlap]
        fam = {}
        for r in rows(RESULTS / where / "calc" / f"{A0}.jsonl"):
            fam.setdefault(r["family"], []).append(r["id"])
        ahead = sum(sum(b[i] for i in ids) > sum(a[i] for i in ids) for ids in fam.values())
        behind = sum(sum(b[i] for i in ids) < sum(a[i] for i in ids) for ids in fam.values())
        out[where] = {"unseen": len(unseen), "A0": sum(a[i] for i in unseen), "A3": sum(b[i] for i in unseen),
                      "A0_only": sum(a[i] and not b[i] for i in unseen),
                      "A3_only": sum(b[i] and not a[i] for i in unseen),
                      "families": len(fam), "A3_ahead": ahead, "A3_behind": behind,
                      "A3_tied": len(fam) - ahead - behind}
    return out


