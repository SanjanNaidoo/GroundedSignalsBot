def rows(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def write_fragment(name: str, body: str) -> None:
    (TABLES / name).write_text("% Generated by scripts/validation_results.py from the result files. Do not edit.\n"
                               + body.rstrip() + "\n", encoding="utf-8", newline="\n")


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if not n:
        return (0.0, 0.0)
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return (max(0.0, centre - half), min(1.0, centre + half))


def met(ok: bool) -> str:
    return r"\cellcolor{ymGreenBg}\textbf{met}" if ok else r"\cellcolor{ymRedBg}\textbf{missed}"


