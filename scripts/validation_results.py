def e33() -> dict | None:
    fix = RESULTS / "followup-fix-amended" / "followup"
    if not (fix / f"{A0}.jsonl").exists() or not (fix / f"{A3}.jsonl").exists():
        print("E33: no amended run yet; followup-fix.tex not written")
        return None
    before_dir = RESULTS / "heldout-gatefix-amended" / "followup"
    retr_before = json.loads((RESULTS / "platform-live" / "run-2026-10-16" / "followup-retractions.json")
                             .read_text(encoding="utf-8"))
    retr_after = json.loads((RESULTS / "followup-fix-amended" / "followup-retractions.json")
                            .read_text(encoding="utf-8"))
    fx4 = json.loads((RESULTS / "followup-fix" / "fx4-check.json").read_text(encoding="utf-8"))
    out, body = {}, []
    for s in (A0, A3):
        b, a = rows(before_dir / f"{s}.jsonl"), rows(fix / f"{s}.jsonl")
        out[s] = {
            "retract_or_note": [retr_before[s]["either"], retr_after[s]["either"]],
            "followup_right": [sum(r["followup_correct"] for r in b), sum(r["followup_correct"] for r in a)],
            "first_full": [sum(r["first_fully_correct"] for r in b), sum(r["first_fully_correct"] for r in a)],
            "n": len(a),
        }
    pass_fx2 = {A0: 50, A3: 51}
    fx = {
        "FX1": all(out[s]["retract_or_note"][1] <= 2 for s in out),
        "FX2": all(out[s]["followup_right"][1] >= pass_fx2[s] for s in out),
        "FX3": all(out[s]["first_full"][1] >= out[s]["first_full"][0] - 2 for s in out),
        "FX4": fx4["single_turn_changed"] == 0,
    }
    label = {A0: "local", A3: "Opus~5"}
    for s in (A0, A3):
        o = out[s]
        body.append(f"FX1 & Second replies retracting the first or carrying the note, {label[s]} & "
                    f"{o['retract_or_note'][0]} & {o['retract_or_note'][1]} & at most 2 \\\\ \\hline")
    for s in (A0, A3):
        o = out[s]
        body.append(f"FX2 & Follow-up value right, {label[s]} & {o['followup_right'][0]} & "
                    f"{o['followup_right'][1]} & at least {pass_fx2[s]} \\\\ \\hline")
    for s in (A0, A3):
        o = out[s]
        body.append(f"FX3 & First answer fully right, {label[s]} & {o['first_full'][0]} & "
                    f"{o['first_full'][1]} & at least {o['first_full'][0] - 2} \\\\ \\hline")
    body.append(f"FX4 & Single-turn, first-turn and benchmark prompts changed & -- & "
                f"{fx4['single_turn_changed']} of {fx4['single_turn_items']} & 0 \\\\ \\hline")
    write_fragment("followup-fix.tex", "\n".join(body))
    return {"by_system": out, "marks": fx, "fx4_items": fx4["single_turn_items"]}


