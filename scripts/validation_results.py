def e32() -> dict:
    s = json.loads((RESULTS / "problems-fresh" / "summary.json").read_text(encoding="utf-8"))
    dev = json.loads((RESULTS / "problems" / "e25c.json").read_text(encoding="utf-8"))["arms"]["fused"]["summary"]
    shown = {r["id"]: r for r in json.loads((RESULTS / "problems-fresh" / "shown.json")
                                            .read_text(encoding="utf-8"))["shown"]}
    judged = {r["query"]: r["scores"] for r in rows(ROOT / "grades" / "problems-fresh.jsonl")}
    misses = withheld = in_top3 = 0
    for qid, scores in judged.items():
        rel = {u for u, v in scores.items() if v >= 2}
        if not rel or rel & set(shown[qid]["shown"]):
            continue
        misses += 1
        withheld += not shown[qid]["shown"]
        in_top3 += bool(rel & set(shown[qid]["withheld_top"]))
    a, k = s["all"], s["by_kind"]
    dev_hits = round(dev["hit_at_3"] * dev["scored"])
    dev_top = round(dev["top_rubric_at_least_2"] * dev["scored"])

    def cell(mark, group=a):
        x, n, (lo, hi) = group[mark]
        return f"{x} of {n} ({100 * lo:.0f}--{100 * hi:.0f}\\%)"

    body = [
        f"R1 & A relevant past question among those shown, of queries with one & {cell('R1')} & "
        f"{dev_hits} of {dev['scored']} & 70\\% & {met(s['marks']['R1'])} \\\\ \\hline",
        f"R2 & The first one shown is relevant & {cell('R2')} & {dev_top} of {dev['scored']} & 60\\% & "
        f"{met(s['marks']['R2'])} \\\\ \\hline",
        f"R3 & Nothing shown, of queries with no relevant question & {cell('R3')} & "
        f"{dev['none_without_reference']} of {dev['none_queries']} & two-thirds & {met(s['marks']['R3'])} \\\\ \\hline",
        f"-- & R1, students' wording & {cell('R1', k['student'])} & -- & -- & -- \\\\ \\hline",
        f"-- & R1, problem statements & {cell('R1', k['statement'])} & -- & -- & -- \\\\ \\hline",
        f"-- & Misses where nothing was shown although a relevant question exists & {withheld} of {misses} & "
        f"-- & -- & -- \\\\ \\hline",
        f"-- & Mean reciprocal rank & {a['MRR']:.2f} & {dev['mrr']:.2f} & -- & -- \\\\ \\hline",
        f"-- & Not-examined predictions borne out & {s['unexamined_predictions_borne_out'][0]} of "
        f"{s['unexamined_predictions_borne_out'][1]} & -- & -- & -- \\\\ \\hline",
    ]
    write_fragment("problems-fresh.tex", "\n".join(body))
    return {"marks": s["marks"], "R1": a["R1"], "R2": a["R2"], "R3": a["R3"], "MRR": a["MRR"],
            "student_R1": k["student"]["R1"], "statement_R1": k["statement"]["R1"],
            "misses": misses, "misses_withheld": withheld, "relevant_in_withheld_top3": in_top3,
            "judged_units": s["judged_units"], "unexamined_borne_out": s["unexamined_predictions_borne_out"],
            "development": {"R1": [dev_hits, dev["scored"]], "R2": [dev_top, dev["scored"]],
                            "R3": [dev["none_without_reference"], dev["none_queries"]], "MRR": round(dev["mrr"], 2)}}


